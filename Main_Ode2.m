clc, clear, close all

% Initialization of the parameters
a=[1 1]; % coefficient for the air resistance
m=90; % mass in kg
h=80; % height in m
g=9.8; % gravity in m/s^2
K=[5 40 500]; % elastic coefficients in N/m of the 3 cords 
n=[0.1, 0.05, 0.01, 0.001]; % step size used for the methods (ode45 excluded)
t_end=10; % end of time span 

%% Appication of the methods

% Conditions for the ode method 
event=odeset('Events',@stop_cond,'RelTol',1e-10);
event2=odeset('RelTol',1e-10);

% Cycle to test the convergence, with different step sizes
for j=1:length(n)  
    figure()
    sgtitle(['Step size s = ', num2str(n(j))])
    % Cycle to compute solution for the 3 different cords
    for i=1:length(K)
        s=n(j);
        % Ode method, in this case is taked as the reference solution to compare and
        % compute the errors generated by the other methods
        [t_ode,x_ode] = ode45(@(t,x)free_motion(t,x,a,m), [0 5],[0 0], event);
        [t_ode2,x_ode2]=ode45(@(t,x)elastic_retraction(t,x,a,m,K(i)), [t_ode(end), t_end], [x_ode(end,1),x_ode(end,2)], event2);
        t_exact = [t_ode; t_ode2];
        x_exact = [x_ode; x_ode2];
        
        % Forward Euler's Method
        [t_exEu,x_exEu]=explicit_Euler(@free_motion,[0,5],30,[0 0]',s,a,m,K(i));
        [t_exEu2,x_exEu2]=explicit_Euler(@elastic_retraction,[t_exEu(end),t_end],200,[x_exEu(end,1),x_exEu(end,2)],s,a,m,K(i));
        x_exEu_interp = spline([t_exEu t_exEu2(2:end)], [x_exEu(:,1); x_exEu2(2:end,1)], t_exact);
    
        % Backward Euler's Method
        [t_impEu,x_impEu]=implicit_Euler(@free_motion,@Jfree,[0,5],[0 0],s,a,m,K(i),30);
        [t_impEu2,x_impEu2]=implicit_Euler(@elastic_retraction,@Jfree,[t_impEu(end),t_end],[x_impEu(end,1) x_impEu(end,2)],s,a,m,K(i),200);
        x_impEu_interp = spline([t_impEu t_impEu2(2:end)], [x_impEu(:,1); x_impEu2(2:end,1)], t_exact);
    
        % Heun's Method
        [t_heun, x_heun]=heun(@free_motion,[0 6],[0, 0], s,30, a, m, K(i));
        [t_heun2, x_heun2]=heun(@elastic_retraction,[t_heun(end) t_end],[x_heun(end,1), x_heun(end,2)], s,200, a, m, K(i));
        x_heun_interp = spline([t_heun t_heun2(2:end)], [x_heun(:,1); x_heun2(2:end,1)], t_exact);
        
        % Computation of the relative errors
        Rerr_exEu(i,j) = norm(x_exEu_interp - x_exact(:,1))/norm(x_exact(:,1));
        Rerr_impEu(i,j) = norm(x_impEu_interp - x_exact(:,1))/norm(x_exact(:,1));
        Rerr_heun(i,j) = norm(x_heun_interp - x_exact(:,1))/norm(x_exact(:,1));
        
        % Comutation of the maximum global errors
        Gerr_exEu(i,j) = max(abs(x_exEu_interp - x_exact(:,1)));
        Gerr_impEu(i,j) = max(abs(x_impEu_interp - x_exact(:,1)));
        Gerr_heun(i,j) = max(abs(x_heun_interp - x_exact(:,1)));

        % Plots for each K 
        subplot(3,1,i)
        title(strcat('Trajectories for K= ', num2str(K(i))))
        hold on
        set(gca, 'DefaultLineLineWidth', 2) 
        plot(t_ode,-x_ode(:,1),'-r',t_ode2,-x_ode2(:,1),'-r')
        plot(t_exEu,-x_exEu(:,1),'-b',t_exEu2,-x_exEu2(:,1),'-b')
        plot(t_impEu,-x_impEu(:,1),'-m',t_impEu2,-x_impEu2(:,1),'-m')
        plot(t_heun,-x_heun(:,1),'-g',t_heun2,-x_heun2(:,1),'-g')
        yline(-h,'--')
        grid
        hold off
        
        ylabel('Height [m]')
        xlabel('Time [s]')
        legend('Ode45','','Explicit Euler','','Implicit Euler','',"Heun's Method",'','ground line')
        
        % Distance from the ground 
        d(i)=min(-x_exact(:,1))+80;

    end
end

%%
%Print the relative errors
disp('Relative rrors with respect ode45 method')
disp(' ')
for i=1:length(K)
    fprintf('K=%d \n', K(i))
    disp(table(n', Rerr_exEu(i,:)', Rerr_impEu(i,:)', Rerr_heun(i,:)',...
    'VariableNames', {'s', 'Explicit_Euler', 'Implicit_Euler', 'Heun'}))
end

%Print the maximum absolute global errors
disp('Global errors with respect ode45 method')
disp(' ')
for i=1:length(K)
    fprintf('K=%d \n', K(i))
    disp(table(n', Gerr_exEu(i,:)', Gerr_impEu(i,:)', Gerr_heun(i,:)',...
    'VariableNames', {'s', 'Explicit_Euler', 'Implicit_Euler', 'Heun'}))
end

%Plot of the relative errors
figure()
for i=1:length(K)
    subplot(3,1,i)
    title(strcat('Relative errors for K= ', num2str(K(i))))
    hold on 
    set(gca, 'DefaultLineLineWidth', 1.5) 
    plot(n,Rerr_exEu(i,:),'-*b')
    plot(n,Rerr_impEu(i,:),'-*m')
    plot(n,Rerr_heun(i,:),'-*g')
    hold off
    legend('Explicit Euler', 'Implicit Euler','Heun')
    ylabel('Relative Error')
    xlabel('Step Size')
    grid
end

